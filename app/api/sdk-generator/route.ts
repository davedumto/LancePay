import { createHash, createHmac } from 'crypto'
import { NextRequest, NextResponse } from 'next/server'
import { z } from 'zod'
import { prisma } from '@/lib/db'
import { logger } from '@/lib/logger'
import { requireWalletActor } from '@/app/api/_lib/collective-wallet-auth'

export const SUPPORTED_SDK_LANGUAGES = ['typescript', 'python', 'go', 'rust'] as const
export type SdkLanguage = (typeof SUPPORTED_SDK_LANGUAGES)[number]

export const SUPPORTED_SDK_API_VERSIONS = ['2026-06-01', '2025-11-01', '2025-05-01'] as const
export type SdkApiVersion = (typeof SUPPORTED_SDK_API_VERSIONS)[number]

export const DEFAULT_SDK_API_VERSION: SdkApiVersion = '2026-06-01'
export const SIGNED_URL_TTL_SECONDS = 15 * 60 // 15 minutes

const sdkRequestSchema = z.object({
  language: z.enum(SUPPORTED_SDK_LANGUAGES, {
    errorMap: () => ({
      message: `Unsupported language. Allowed values: ${SUPPORTED_SDK_LANGUAGES.join(', ')}`,
    }),
  }),
  apiVersion: z.string().trim().default(DEFAULT_SDK_API_VERSION),
})

interface OpenApiOperationSpec {
  path: string
  method: 'GET' | 'POST' | 'PATCH' | 'DELETE'
  operationId: string
  requestType?: string
  responseType: string
  introducedIn: SdkApiVersion
}

const LIVE_OPENAPI_OPERATIONS: readonly OpenApiOperationSpec[] = Object.freeze([
  {
    path: '/api/invoices',
    method: 'GET',
    operationId: 'listInvoices',
    responseType: 'InvoiceListResponse',
    introducedIn: '2025-05-01',
  },
  {
    path: '/api/invoices',
    method: 'POST',
    operationId: 'createInvoice',
    requestType: 'CreateInvoiceRequest',
    responseType: 'InvoiceResponse',
    introducedIn: '2025-05-01',
  },
  {
    path: '/api/webhook-deliveries/stats',
    method: 'GET',
    operationId: 'getWebhookDeliveryStats',
    responseType: 'WebhookStatsResponse',
    introducedIn: '2025-11-01',
  },
  {
    path: '/api/developer-portal/sandbox-sessions',
    method: 'POST',
    operationId: 'createSandboxSession',
    requestType: 'CreateSandboxSessionRequest',
    responseType: 'SandboxSessionResponse',
    introducedIn: '2026-06-01',
  },
])

export interface StoredSdkBundle {
  bundleHash: string
  language: SdkLanguage
  apiVersion: SdkApiVersion
  specRevision: string
  fileCount: number
  sizeBytes: number
  createdAt: Date
  files: Record<string, string>
}

const sdkBundleMemoryCache = new Map<string, StoredSdkBundle>()

export function clearSdkBundleCache(): void {
  sdkBundleMemoryCache.clear()
}

export function computeLiveSpecRevision(apiVersion: SdkApiVersion): {
  specRevision: string
  operations: OpenApiOperationSpec[]
} {
  const operations = LIVE_OPENAPI_OPERATIONS.filter((op) => op.introducedIn <= apiVersion)
  const canonicalSpec = JSON.stringify({
    openapi: '3.1.0',
    apiVersion,
    operations,
  })
  const specRevision = createHash('sha256')
    .update(canonicalSpec, 'utf8')
    .digest('hex')
    .slice(0, 16)
  return { specRevision, operations }
}

export function computeSdkBundleHash(
  language: SdkLanguage,
  apiVersion: SdkApiVersion,
  specRevision: string
): string {
  return createHash('sha256')
    .update(`${language}:${apiVersion}:${specRevision}`, 'utf8')
    .digest('hex')
}

export function synthesizeTypedSdkFiles(
  language: SdkLanguage,
  apiVersion: SdkApiVersion,
  specRevision: string,
  operations: OpenApiOperationSpec[]
): Record<string, string> {
  const header = `// Auto-generated by LancePay SDK Generator (apiVersion=${apiVersion}, rev=${specRevision})\n`

  if (language === 'typescript') {
    const methods = operations
      .map(
        (op) =>
          `  async ${op.operationId}(${op.requestType ? `body: ${op.requestType}` : ''}): Promise<${op.responseType}> {\n` +
          `    return this.request('${op.method}', '${op.path}'${op.requestType ? ', body' : ''});\n  }`
      )
      .join('\n\n')
    return {
      'package.json': JSON.stringify(
        { name: '@lancepay/sdk', version: `1.0.0-${apiVersion}`, type: 'module' },
        null,
        2
      ),
      'src/models.ts': `${header}export interface InvoiceResponse { id: string; amount: string; currency: string; status: string; }\nexport interface InvoiceListResponse { invoices: InvoiceResponse[]; }\nexport interface CreateInvoiceRequest { clientEmail: string; amount: string; currency: string; }\nexport interface WebhookStatsResponse { stats: unknown[]; flagged: string[]; }\nexport interface CreateSandboxSessionRequest { apiKeyId: string; ttlSeconds?: number; }\nexport interface SandboxSessionResponse { session: Record<string, unknown>; data: Record<string, unknown>; }\n`,
      'src/client.ts': `${header}import type { InvoiceListResponse, InvoiceResponse, CreateInvoiceRequest, WebhookStatsResponse, CreateSandboxSessionRequest, SandboxSessionResponse } from './models';\nexport class LancePayClient {\n  constructor(private readonly apiKey: string, private readonly baseUrl = 'https://api.lancepay.io') {}\n  private async request<T>(method: string, path: string, body?: unknown): Promise<T> {\n    const res = await fetch(this.baseUrl + path, { method, headers: { 'X-API-Key': this.apiKey, 'LancePay-Version': '${apiVersion}', 'Content-Type': 'application/json' }, body: body ? JSON.stringify(body) : undefined });\n    return res.json() as Promise<T>;\n  }\n${methods}\n}\n`,
    }
  }

  if (language === 'python') {
    const methods = operations
      .map(
        (op) =>
          `    def ${op.operationId}(self${op.requestType ? ', payload: dict' : ''}) -> dict:\n` +
          `        return self._request("${op.method}", "${op.path}"${op.requestType ? ', payload' : ''})`
      )
      .join('\n\n')
    return {
      'pyproject.toml': `[project]\nname = "lancepay-sdk"\nversion = "1.0.0"\n`,
      'lancepay/client.py': `# ${header}class LancePayClient:\n    API_VERSION = "${apiVersion}"\n${methods}\n`,
    }
  }

  if (language === 'go') {
    return {
      'go.mod': `module github.com/lancepay/lancepay-go\n\ngo 1.22\n`,
      'client.go': `${header}package lancepay\n\nconst DefaultAPIVersion = "${apiVersion}"\nconst SpecRevision = "${specRevision}"\n`,
    }
  }

  return {
    'Cargo.toml': `[package]\nname = "lancepay-sdk"\nversion = "1.0.0"\nedition = "2021"\n`,
    'src/lib.rs': `${header}pub const API_VERSION: &str = "${apiVersion}";\npub const SPEC_REVISION: &str = "${specRevision}";\n`,
  }
}

export function createSignedBundleDownloadUrl(
  bundleHash: string,
  language: SdkLanguage,
  apiVersion: SdkApiVersion,
  expiresAt: Date
): string {
  const secret = process.env.SDK_DOWNLOAD_SIGNING_SECRET || 'lancepay-sdk-signing-secret-v1'
  const expiresUnix = Math.floor(expiresAt.getTime() / 1000)
  const artifactPath = `/sdk-bundles/${bundleHash}/lancepay-${language}-sdk-${apiVersion}.tar.gz`
  const signature = createHmac('sha256', secret)
    .update(`${artifactPath}:${expiresUnix}`, 'utf8')
    .digest('hex')
  return `https://cdn.lancepay.io${artifactPath}?expires=${expiresUnix}&sig=${signature}`
}

/**
 * POST /api/sdk-generator
 * Builds or retrieves a cached typed client SDK bundle from the live OpenAPI spec
 * keyed by SHA-256(language, apiVersion, specRevision) and returns a short-lived
 * signed download URL without inlining the bundle contents in the response.
 */
export async function POST(request: NextRequest) {
  try {
    const auth = await requireWalletActor(request)
    if ('response' in auth) return auth.response
    const { actor } = auth

    let rawBody: unknown
    try {
      rawBody = await request.json()
    } catch {
      return NextResponse.json({ error: 'Invalid JSON body' }, { status: 400 })
    }

    const parsed = sdkRequestSchema.safeParse(rawBody)
    if (!parsed.success) {
      return NextResponse.json(
        { error: 'Invalid request body', details: parsed.error.flatten().fieldErrors },
        { status: 400 }
      )
    }

    const { language, apiVersion } = parsed.data

    if (!SUPPORTED_SDK_API_VERSIONS.includes(apiVersion as SdkApiVersion)) {
      return NextResponse.json(
        {
          error: `Unsupported or sunset API version "${apiVersion}"`,
          code: 'UNSUPPORTED_API_VERSION',
          supportedVersions: SUPPORTED_SDK_API_VERSIONS,
        },
        { status: 400 }
      )
    }

    const version = apiVersion as SdkApiVersion
    const { specRevision, operations } = computeLiveSpecRevision(version)
    const bundleHash = computeSdkBundleHash(language, version, specRevision)

    const now = new Date()
    const expiresAt = new Date(now.getTime() + SIGNED_URL_TTL_SECONDS * 1000)

    // 1. Check Prisma sdkBundle model (if present) or in-memory cache
    const dbModel = (prisma as any)?.sdkBundle
    let existingBundle: StoredSdkBundle | null = sdkBundleMemoryCache.get(bundleHash) ?? null

    if (!existingBundle && dbModel && typeof dbModel.findUnique === 'function') {
      const dbRow = await dbModel.findUnique({ where: { bundleHash } })
      if (dbRow) {
        existingBundle = {
          bundleHash: dbRow.bundleHash,
          language: dbRow.language,
          apiVersion: dbRow.apiVersion,
          specRevision: dbRow.specRevision,
          fileCount: dbRow.fileCount,
          sizeBytes: dbRow.sizeBytes,
          createdAt: dbRow.createdAt ?? now,
          files: dbRow.files ?? {},
        }
        sdkBundleMemoryCache.set(bundleHash, existingBundle)
      }
    }

    let cached = true
    let bundle = existingBundle

    if (!bundle) {
      cached = false
      const files = synthesizeTypedSdkFiles(language, version, specRevision, operations)
      const fileEntries = Object.entries(files)
      const sizeBytes = fileEntries.reduce(
        (sum, [name, content]) => sum + Buffer.byteLength(name) + Buffer.byteLength(content),
        0
      )

      bundle = {
        bundleHash,
        language,
        apiVersion: version,
        specRevision,
        fileCount: fileEntries.length,
        sizeBytes,
        createdAt: now,
        files,
      }

      if (dbModel && typeof dbModel.create === 'function') {
        await dbModel.create({
          data: {
            bundleHash,
            language,
            apiVersion: version,
            specRevision,
            fileCount: bundle.fileCount,
            sizeBytes: bundle.sizeBytes,
            createdByUserId: actor.id,
          },
        })
      }

      sdkBundleMemoryCache.set(bundleHash, bundle)
    }

    const downloadUrl = createSignedBundleDownloadUrl(bundleHash, language, version, expiresAt)

    logger.info(
      { userId: actor.id, language, apiVersion: version, bundleHash, cached },
      'SDK bundle generated'
    )

    return NextResponse.json(
      {
        bundleHash,
        language,
        apiVersion: version,
        specRevision,
        cached,
        fileCount: bundle.fileCount,
        sizeBytes: bundle.sizeBytes,
        downloadUrl,
        expiresAt: expiresAt.toISOString(),
      },
      { status: cached ? 200 : 201 }
    )
  } catch (error) {
    logger.error({ err: error }, 'POST /api/sdk-generator error')
    return NextResponse.json({ error: 'Failed to generate SDK bundle' }, { status: 500 })
  }
}
